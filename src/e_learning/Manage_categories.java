    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        jfc=new JFileChooser();
        int ans=jfc.showOpenDialog(this);
        
        if(ans==JFileChooser.APPROVE_OPTION)
        {
            ph=jfc.getSelectedFile();
            ImageIcon ic=new ImageIcon(ph.getPath());// imageicon will have to pass the path not file(ph)
            // after resize it
            Image img=ic.getImage().getScaledInstance(photolb.getWidth(), photolb.getHeight(), Image.SCALE_SMOOTH);
            // make new imageicon bez img not apply on label
            ImageIcon ic1=new ImageIcon(img);
            photolb.setIcon(ic1);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String category1=category.getText();
        String ans=myClient.addCategories(category1, ph);
        if(ans.trim().equals("success"))
        {
            JOptionPane.showMessageDialog(rootPane, "Added Successfully");
            category.setText("");
            photolb.setIcon(null);
            load_category();
            tm.fireTableDataChanged();//it is use for when i add new entry in the table it will reflect change in the database on the gui table

        }
        else{
            JOptionPane.showMessageDialog(rootPane, ans);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
            int ans=jTable1.getSelectedRow();
            if(ans==-1)
            {
                JOptionPane.showMessageDialog(rootPane, "Please Select The Row");
            }
            else
            {
                String ans1=myClient.deletecat(al.get(ans).name);
                if(ans1.trim().equals("Success"))
                {
                   JOptionPane.showMessageDialog(rootPane, "Row Deleted Successfully");
                   load_category();
                   tm.fireTableDataChanged();
                }
                else
                {
                   JOptionPane.showMessageDialog(rootPane, "Abort");
                    
                }
            }
        
    }//GEN-LAST:event_jButton3ActionPerformed

