    void load_category()
    {
        al.clear(); //to show data in table one time to make al empty
        String ans=myClient.fetchCat();
        System.out.println(ans);
        StringTokenizer st=new StringTokenizer(ans,";;");
         while(st.hasMoreTokens())
         {
             String row=st.nextToken();
             StringTokenizer st1=new StringTokenizer(row,"$");
             String name=st1.nextToken();
             String photo=st1.nextToken(); 
             al.add(new category(name,photo));
         }
    }
    class myTableModel extends AbstractTableModel
    {

        @Override
        public int getRowCount() {
           return al.size();
        }

        @Override
        public int getColumnCount() {
            return 2;
        }

        @Override
        public Object getValueAt(int rowIndex, int columnIndex) {
           if(columnIndex==0)
           {
               return al.get(rowIndex).name;
           }
           else{
                return al.get(rowIndex).photo;

           }
        }
        
    }
